using System.Collections.Generic;

namespace Neoxider.DurableQueue.Ports
{
    /// <summary>
    /// Перевод очереди в строку и обратно. Порт, потому что сериализатор и — важнее — САМ ФОРМАТ
    /// принадлежат приложению: у переезжающей на библиотеку очереди уже есть формат, который лежит
    /// на устройствах живых пользователей, и менять его ради красоты значит терять их данные.
    ///
    /// <para><b>Единица перевода — вся очередь, а не одна запись, и это следствие
    /// <see cref="IQueueStorage"/>:</b> у ключа ровно одно строковое значение. Кодек «одна запись —
    /// одна строка» вынудил бы хранить массив экранированных строк — формат, которого не бывает ни у
    /// одной существующей очереди и который нельзя прочитать глазами при разборе жалобы.</para>
    /// </summary>
    public interface IQueueCodec<T>
    {
        public string Encode(IReadOnlyList<QueueRecord<T>> records);

        /// <summary>
        /// <c>false</c> — содержимое не разбирается. Тогда очередь пишет об этом в журнал и удаляет
        /// битое значение: молча вернуть «записей нет» — значит потерять данные так, что этого не
        /// видно ни в логах, ни в диагностике, а битое значение продолжает лежать в хранилище.
        /// </summary>
        public bool TryDecode(string raw, out List<QueueRecord<T>> records);
    }
}
