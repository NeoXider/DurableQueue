using System.Threading;
using Cysharp.Threading.Tasks;

namespace Neoxider.DurableQueue.Ports
{
    /// <summary>
    /// Доставка ПАЧКИ записей одного вида. Отдельный от транспорта порт нужен ровно там, где один
    /// запрос собирается из нескольких записей или где у приложения уже есть типизированный клиент,
    /// который незачем обходить: без него батчинг «N записей — один запрос» пришлось бы
    /// переизобретать внутри библиотеки, а она не знает ни одного адреса.
    ///
    /// <para><b>Обязанность реализации, а не библиотеки: превратить исход типизированного клиента в
    /// <see cref="QueueResponse"/>.</b> Клиент, который бросает своё исключение вместо кода ответа,
    /// обязан быть перехвачен здесь — код, тело и заголовки кладутся в ответ, а необъявленное
    /// исключение становится транспортной ошибкой. Иначе диспетчер и транспорт дают политике разный
    /// вход, и отказ сервера до классификации просто не доедет.</para>
    /// </summary>
    public interface IQueueDispatcher<T>
    {
        public UniTask<QueueResponse> DeliverAsync(QueueBatch<T> batch, CancellationToken cancellationToken);
    }
}
