namespace Neoxider.DurableQueue.Ports
{
    /// <summary>
    /// Журнал библиотеки. Порт, потому что фасад логирования — тип приложения; писать в консоль
    /// движка напрямую библиотека не имеет права, иначе её сообщения не попадут ни в фильтры, ни в
    /// диагностику хозяина.
    ///
    /// <para>Уровня два, и оба обязательны по смыслу: <see cref="Warn"/> — «данные пока не уехали»,
    /// <see cref="Error"/> — «данные потеряны или отвергнуты навсегда». Уровня «всё хорошо» здесь
    /// нет намеренно: успешная доставка — не событие библиотеки, а событие приложения, и решать,
    /// шуметь ли о ней, ему.</para>
    ///
    /// <para><b>Содержимое записей в журнал не попадает никогда</b> — только вид, поток, ключ
    /// идемпотентности, счётчики и код ошибки. Полезная нагрузка может быть чем угодно, включая
    /// персональные данные, а журнал живёт дольше очереди.</para>
    /// </summary>
    public interface IQueueLog
    {
        public void Warn(string message);

        public void Error(string message);
    }
}
