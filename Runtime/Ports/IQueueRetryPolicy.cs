namespace Neoxider.DurableQueue.Ports
{
    /// <summary>
    /// Классификация исхода отправки. Порт, а не зашитый список кодов: коды и их смысл принадлежат
    /// конкретному серверу, и стоит внести их внутрь — библиотека перестаёт быть общей.
    ///
    /// <para>Политика вызывается на КАЖДЫЙ ответ, включая успешный: «доставлено» — тоже вердикт, и
    /// принимает его тот, кто знает контракт сервера. Библиотека оставляет себе только форму ответа
    /// и то, что она с этим ответом делает.</para>
    /// </summary>
    public interface IQueueRetryPolicy
    {
        public QueueRetryDecision Decide(QueueAttempt attempt);
    }
}
