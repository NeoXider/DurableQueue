namespace Neoxider.DurableQueue.Ports
{
    /// <summary>
    /// Хранилище пары «ключ — строка». Порт, потому что способ хранения платформенный: у одного
    /// приложения это префы движка, у другого файл, у третьего браузерная база или чужой KV. В
    /// библиотеку приходит просто строковый ключ — кому он принадлежит и как скоупится, решает
    /// вызывающий.
    /// </summary>
    public interface IQueueStorage
    {
        /// <summary>
        /// Есть ли у ключа адрес прямо сейчас. Отделяет «данных нет» от «спрашивать ещё рано»:
        /// ключ часто скоупится по владельцу данных, а владелец на старте неизвестен, и тогда
        /// <see cref="TryRead"/> честно отвечает <c>false</c> в обоих случаях. Без этого признака
        /// очередь закрепит пустоту как «записей нет» и первой же записью затрёт сохранённое —
        /// дефект, который в одном проекте уже стоил истории прогресса.
        /// </summary>
        public bool IsAddressable(string key);

        /// <summary><c>false</c> — записи нет или ключ ещё неадресуем.</summary>
        public bool TryRead(string key, out string value);

        /// <summary>
        /// Пишет значение. <c>false</c> — хранилище записать отказалось (переполнение, квота).
        /// Возврат вместо исключения здесь принципиален: отказ хранилища обязан превратиться в
        /// отказ ПОСТАНОВКИ, который вызывающий увидит, а не в исключение, прилетевшее из кадра
        /// геймплея тому, кто «просто записал факт». Реализация ловит своё исключение сама;
        /// очередь на всякий случай ловит его тоже, но полагаться на это не следует.
        /// </summary>
        public bool Write(string key, string value);

        public void Delete(string key);

        /// <summary>
        /// Сброс на долговременный носитель. Отделён от <see cref="Write"/> намеренно: на части
        /// платформ это синхронная операция ценой в подвисший кадр, поэтому очередь зовёт его не на
        /// каждую запись, а только там, где потеря последних миллисекунд недопустима.
        /// </summary>
        public void Flush();
    }
}
